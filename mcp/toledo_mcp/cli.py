def cmd_find(args: argparse.Namespace) -> None:
    c = cache_mod.get_cache()
    try:
        rows = c.search(
            args.query, root=args.root, domain=args.domain, tier=args.tier,
            status=args.status, coq_status=args.coq_status, regex=args.regex,
            limit=args.limit,
        )
    except (regex_guard.RegexQueryTooLong, regex_guard.RegexTimeout) as exc:
        # SEC-1 fix (2026-09-07): same guard as `toledo_search` over MCP —
        # `--regex` is agent/user-supplied and unbounded regex.search() over
        # unbounded registry text can hang the whole process; fail with a
        # clear CLI error instead of hanging or crashing with a traceback.
        _die(str(exc))
        return  # unreachable, _die raises; keeps type-checkers happy
    _emit_rows(_rows_with_verdict(c, rows), args.format)


def cmd_show(args: argparse.Namespace) -> None:
    c = cache_mod.get_cache()
    result = _attach_verdict(c, c.get(args.code))
    if result is None:
        _die(f"code not found: {args.code}")
    _emit(result)


def cmd_ancestry(args: argparse.Namespace) -> None:
    c = cache_mod.get_cache()
    if c.get(args.code) is None:
        _die(f"code not found: {args.code}")
    chain = c.ancestry_chain(args.code)
    print(" -> ".join(chain))


def cmd_descendants(args: argparse.Namespace) -> None:
    c = cache_mod.get_cache()
    if c.get(args.code) is None:
        _die(f"code not found: {args.code}")
    rows = c.descendants(args.code)
    _emit_rows(_rows_with_verdict(c, rows), args.format)


def cmd_neighbours(args: argparse.Namespace) -> None:
    c = cache_mod.get_cache()
    if c.get(args.code) is None:
        _die(f"code not found: {args.code}")
    rows = c.neighbours(args.code, rel_type=args.type)
    # No per-row verdict here — these are relation edges, not citable
    # entries; see _row_with_verdict's docstring.
    _emit_rows(rows, args.format)


def cmd_by_root(args: argparse.Namespace) -> None:
    c = cache_mod.get_cache()
    rows = c.by_root(args.root, limit=args.limit)
    _emit_rows(_rows_with_verdict(c, rows), args.format)


def cmd_by_domain(args: argparse.Namespace) -> None:
    c = cache_mod.get_cache()
    rows = c.by_domain(args.domain, limit=args.limit)
    _emit_rows(_rows_with_verdict(c, rows), args.format)


def cmd_by_record(args: argparse.Namespace) -> None:
    c = cache_mod.get_cache()
    rows = c.by_record(args.record_id)
    _emit_rows(_rows_with_verdict(c, rows), args.format)


def cmd_export(args: argparse.Namespace) -> None:
    """Unlike `scripts/toledo export` (which reads the generated
    `registry/TOLEDO.json`/`graph/toledo.graphml` files verbatim), `json`/
    `md` here are built fresh from the cached registry so they never lag a
    `make build` run; `graphml` has no cache-layer equivalent to rebuild
    from (it is the registry-owning lane's own generated artifact) and is
    read straight from `graph/toledo.graphml` if present, exactly as
    `scripts/toledo export --format graphml` already does."""
    c = cache_mod.get_cache()
    c.ensure_fresh()
    entries = core.sort_codes(list(c.registry.entries))
    if args.format == "json":
        _emit({"canonical": entries})
    elif args.format == "md":
        for e in entries:
            print(f"## {e['code']} — {e.get('name', '')}")
            print()
            print((e.get("statement") or {}).get("latest", ""))
            print()
    elif args.format == "graphml":
        graph_path = paths.repo_root() / "graph" / "toledo.graphml"
        if not graph_path.exists():
            _die(f"{graph_path} not found — run scripts/toledo_build.py first", code=2)
        print(graph_path.read_text(encoding="utf-8"))


