def _add_format(p: argparse.ArgumentParser) -> None:
    p.add_argument("--format", choices=["json", "toon"], default="json",
                    help="json (default) or toon (mcp/DESIGN.md sec. 7 — uniform "
                         "row lists only; see this workspace's toon-format skill)")


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(
        prog="toledo",
        description=(
            "toledo_mcp's own CLI over the cached/indexed Toledo registry. "
            "Founder rule (2026-09-07): every equation must be looked up here "
            "before it is used; never use a result whose verdict is not usable."
        ),
    )
    sub = ap.add_subparsers(dest="command", required=True)

    p = sub.add_parser("find", help="search code/aliases/name/statement, optionally filtered")
    p.add_argument("query", nargs="?", default="")
    p.add_argument("--root", default=None)
    p.add_argument("--domain", default=None)
    p.add_argument("--tier", default=None)
    p.add_argument("--status", default=None)
    p.add_argument("--coq-status", dest="coq_status", default=None)
    p.add_argument("--regex", action="store_true")
    p.add_argument("--limit", type=int, default=20,
                    help="0 or omitted = default of 20 (never unlimited); negative is an error")
    _add_format(p)
    p.set_defaults(func=cmd_find)

    p = sub.add_parser("show", help="one code's full entry + verdict")
    p.add_argument("code")
    p.set_defaults(func=cmd_show)

    p = sub.add_parser("ancestry", help="root-first chain from the Genesis root to a code")
    p.add_argument("code")
    p.set_defaults(func=cmd_ancestry)

    p = sub.add_parser("descendants", help="every code reachable via children[] edges")
    p.add_argument("code")
    _add_format(p)
    p.set_defaults(func=cmd_descendants)

    p = sub.add_parser("neighbours", help="direct parent/child/relation neighbours (+ reverse relations)")
    p.add_argument("code")
    p.add_argument("--type", default=None)
    _add_format(p)
    p.set_defaults(func=cmd_neighbours)

    p = sub.add_parser("by-root", help="every code under a given root")
    p.add_argument("root")
    p.add_argument("--limit", type=int, default=None,
                    help="0 or omitted = uncapped (every matching entry); negative is an error")
    _add_format(p)
    p.set_defaults(func=cmd_by_root)

    p = sub.add_parser("by-domain", help="every code in a given domain letter")
    p.add_argument("domain")
    p.add_argument("--limit", type=int, default=None,
                    help="0 or omitted = uncapped (every matching entry); negative is an error")
    _add_format(p)
    p.set_defaults(func=cmd_by_domain)

    p = sub.add_parser("by-record", help="every code occurring in a given Zenodo record id/doi")
    p.add_argument("record_id")
    _add_format(p)
    p.set_defaults(func=cmd_by_record)

    p = sub.add_parser("export", help="export the cached registry (json/md), or graph/toledo.graphml verbatim")
    p.add_argument("--format", choices=["json", "graphml", "md"], required=True)
    p.set_defaults(func=cmd_export)

    p = sub.add_parser("check", help="FOUNDER RULE: verdict for a formula or an exact code")
    p.add_argument("--formula", default=None)
    p.add_argument("--code", default=None)
    p.add_argument("--limit", type=int, default=5,
                    help="0 or omitted = default of 5 (never empty); negative is an error")
    p.add_argument("--method", choices=["phi", "difflib"], default="phi")
    p.set_defaults(func=cmd_check)

    p = sub.add_parser("status", help="compact tier/status/coq_status/verdict readout for one code")
    p.add_argument("code")
    p.set_defaults(func=cmd_status)

    p = sub.add_parser("index-status", help="this build's index health/versioning readout")
    p.set_defaults(func=cmd_index_status)

    p = sub.add_parser("show-verdict-rules", help="introspect the verdict decision table (verdict.py)")
    p.set_defaults(func=cmd_show_verdict_rules)

    p_proposals = sub.add_parser("proposals", help="submitted registration proposals")
    proposals_sub = p_proposals.add_subparsers(dest="proposals_command", required=True)

    p = proposals_sub.add_parser("list", help="list proposals, newest first")
    p.add_argument("--status", default=None, choices=["PENDING", "ACCEPTED", "REJECTED", "SUPERSEDED"])
    p.add_argument("--limit", type=int, default=50,
                    help="0 or omitted = default of 50 (never unlimited); negative is an error")
    _add_format(p)
    p.set_defaults(func=cmd_proposals_list)

    p = proposals_sub.add_parser("show", help="one proposal's full document + lifecycle status")
    p.add_argument("path")
    p.set_defaults(func=cmd_proposals_show)

    p = sub.add_parser("register-proposal", help="FOUNDER RULE: submit a proposal for an unregistered equation")
    p.add_argument("--from-json", dest="from_json", required=True,
                    help="a JSON file shaped like mcp/DESIGN.md sec. 6's proposal object (or its bare fields)")
    p.set_defaults(func=cmd_register_proposal)

    return ap


def main(argv: list[str] | None = None) -> int:
    ap = build_parser()
    args = ap.parse_args(argv)
    args.func(args)
    return 0


