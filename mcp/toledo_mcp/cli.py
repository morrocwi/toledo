def cmd_check(args: argparse.Namespace) -> None:
    """Mirrors `server.py`'s `toledo_check` tool body (see module docstring
    for why this is a deliberate, checked duplication rather than an
    import)."""
    if bool(args.formula) == bool(args.code):
        _emit({
            "verdict": "AMBIGUOUS", "usable": False,
            "reason": "pass exactly one of --formula or --code, not both and not neither.",
            "redirect": [], "candidates": [],
        })
        return
    c = cache_mod.get_cache()
    c.ensure_fresh()
    if args.code:
        entry = c.get(args.code)
        _emit(verdict.verdict_for_check(entry, [], _resolver(c)).to_dict())
        return
    if args.method == "difflib":
        # R3-1 fix (2026-09-07): mirrors server.py's toledo_check fix (see
        # its own comment for the full reasoning) — a "registered" verdict
        # from `core.check`'s bare similarity threshold used to map straight
        # to REGISTERED_CURRENT/usable=True with no check of the matched
        # entry's own `status`. Resolve the top match and delegate to the
        # same status-aware `verdict.verdict_for_entry` a code lookup goes
        # through, instead of trusting the threshold alone.
        result = core.check(c.registry, args.formula, limit=args.limit)
        if result["verdict"] == "registered":
            # R3-3 fix (2026-09-07): mirrors server.py's toledo_check fix
            # (see its own comment for the full reasoning) — `matches[0]`
            # used to be picked blindly even when two or more DIFFERENT
            # codes tied at the top similarity score. Report AMBIGUOUS
            # naming every tied code instead of resolving just the first.
            top_score = result["matches"][0]["similarity"] if result["matches"] else None
            tied_codes = sorted({
                m["code"] for m in result["matches"]
                if m.get("similarity") == top_score
            }) if top_score is not None else []
            if len(tied_codes) > 1:
                _emit({
                    "verdict": "AMBIGUOUS", "usable": False,
                    "reason": (
                        f"core.check (difflib) found {len(tied_codes)} different codes tied at "
                        f"similarity {top_score} — this statement is registered under several "
                        f"codes: {tied_codes} — escalate to a human, do not pick one."
                    ),
                    "redirect": [], "candidates": result["matches"],
                })
                return
            top_match = result["matches"][0] if result["matches"] else None
            top_code = top_match.get("code") if top_match else None
            matched_entry = c.registry.by_code.get(top_code) if top_code else None
            if matched_entry is None:
                _emit({
                    "verdict": "AMBIGUOUS", "usable": False,
                    "reason": (
                        f"core.check (difflib) reported a registered match to {top_code!r} but it "
                        "could not be re-resolved to a full entry — escalate to a human."
                    ),
                    "redirect": [], "candidates": result["matches"],
                })
                return
            v = verdict.verdict_for_entry(matched_entry, _resolver(c))
            _emit({
                "verdict": v.verdict, "usable": v.usable,
                "reason": f"core.check (difflib) best_score={result['best_score']}; {v.reason}",
                "redirect": v.redirect, "candidates": result["matches"],
            })
            return
        mapped = {
            "candidate - confirm": "CANDIDATE_MATCH",
            "not found - must register before use": "NOT_REGISTERED",
        }[result["verdict"]]
        _emit({
            "verdict": mapped, "usable": False,
            "reason": f"core.check (difflib) best_score={result['best_score']}",
            "redirect": [], "candidates": result["matches"],
        })
        return
    candidates = c.find_equivalence_candidates(args.formula, limit=args.limit)
    _emit(verdict.verdict_for_check(None, candidates, _resolver(c)).to_dict())


def cmd_status(args: argparse.Namespace) -> None:
    c = cache_mod.get_cache()
    entry = c.get(args.code)
    summary = c.status(args.code)
    if entry is None or summary is None:
        _emit(None)
        return
    v = verdict.verdict_for_entry(entry, _resolver(c))
    _emit({**summary, "verdict": v.verdict, "usable": v.usable, "verdict_reason": v.reason, "redirect": v.redirect})


def cmd_index_status(args: argparse.Namespace) -> None:
    _emit(cache_mod.get_cache().index_status())


def cmd_show_verdict_rules(args: argparse.Namespace) -> None:
    """Wraps the same introspection `mcp/DESIGN.md` sec. 8 specifies as the
    `toledo_show_verdict_rules` MCP tool. As of this build, `verdict.py`
    (owned by S2) has not yet landed the `RULES`/`_KNOWN_STATUSES` module
    data that section describes — confirmed by `getattr` below, not
    assumed. Rather than hand-typing a second copy of the rule table here
    (which is exactly the drift `mcp/DESIGN.md` sec. 8 says `RULES` exists
    to prevent), this reports that honestly instead of fabricating a table
    that is not actually the code's own decision path. See
    `tests/test_cli.py::test_show_verdict_rules_activates_once_verdict_py_exposes_rules`
    for the pinned expectation once S2 lands it."""
    rules = getattr(verdict, "RULES", None)
    known = getattr(verdict, "_KNOWN_STATUSES", None)
    values = getattr(verdict, "VERDICT_VALUES", None)
    if rules is None or known is None or values is None:
        _emit({
            "available": False,
            "reason": (
                "verdict.py does not yet expose RULES/_KNOWN_STATUSES/"
                "VERDICT_VALUES on this build (mcp/DESIGN.md sec. 8, graft "
                "A6) — pending that module's own owner; nothing here "
                "fabricates a rule table that is not the code's real "
                "decision path."
            ),
        })
        return
    _emit({"available": True, "statuses": sorted(known), "verdict_values": list(values), "rules": rules})


def cmd_proposals_list(args: argparse.Namespace) -> None:
    root = paths.repo_root()
    rows = proposals.list_proposals(status=args.status, limit=args.limit, root=root)
    _emit_rows(rows, args.format)


def cmd_proposals_show(args: argparse.Namespace) -> None:
    root = paths.repo_root()
    doc = proposals.get_proposal(args.path, root=root)
    if doc is None:
        _die(f"no proposal at path: {args.path}")
    _emit(doc)


def cmd_register_proposal(args: argparse.Namespace) -> None:
    """Reads a JSON file shaped like `mcp/DESIGN.md` sec. 6's proposal
    object — either the whole `{"proposal": {...}, ...}` document a prior
    `register-proposal`/`toledo_register_proposal` call produced, or just
    the bare `fields` object it wraps — and calls the same
    `core.register_proposal` the MCP tool does, then records the same
    `PENDING` ledger row `server.py`'s `toledo_register_proposal` does."""
    src = pathlib.Path(args.from_json)
    if not src.exists():
        _die(f"no such file: {src}")
    try:
        raw = json.loads(src.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        _die(f"{src} is not valid JSON: {exc}")
        return  # unreachable, _die raises; keeps type-checkers happy
    fields = raw.get("proposal", raw) if isinstance(raw, dict) else raw
    root = paths.repo_root()
    result = core.register_proposal(fields, repo_root=root)
    proposals.record_submitted(result["path"], result["slug"], result["submitted_at"], root=root)
    _emit(result)


