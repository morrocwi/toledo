#!/usr/bin/env python3
"""toledo_mcp.cli — the `toledo` console-script CLI, S3 (mcp/DESIGN.md secs.
8/14).

Relationship to `scripts/toledo` (unchanged, untouched by this package):
that script is the registry-owning lane's own build-verification CLI — it
reads strictly `registry/TOLEDO.json` (a generated artifact) fresh on every
invocation, and stays exactly as it is. This module is a NEW, separate,
mcp-package-owned CLI that answers the same core verbs
(`find/show/ancestry/descendants/neighbours/by-root/by-domain/by-record/
export`) from the cached/indexed layer this package already built for the
MCP server (`cache.py`/`queries.py`), plus the verdict-aware subcommands
`scripts/toledo` never had (`check`, `status`, `proposals list/show`,
`register-proposal`, `index-status`, `show-verdict-rules`). Two genuine,
disclosed behavioural differences from `scripts/toledo`, not silently
presented as a drop-in replacement:

1. This CLI answers from `registry/CANONICAL.json` via the cache, so a code
   that is stale in `registry/TOLEDO.json` (not yet regenerated by `make
   build`) but present in `CANONICAL.json` is still found here.
2. `show`/`ancestry` and every row-list command attach the founder-rule
   `verdict` this package exists to enforce (2026-09-07: every equation
   must be looked up in Toledo before it is used) — `scripts/toledo show`
   only ever printed the bare entry.

`toledo_check`'s logic is intentionally duplicated here (not imported from
`server.py`) rather than the other way around: `server.py` imports THIS
module's TOON encoder (mcp/DESIGN.md sec. 7, graft B5/C7), so `cli.py` must
not import `server.py` back — that would be a cycle. Keep `cmd_check` in
step with `server.py`'s `toledo_check` by hand if either changes; both are
thin wrappers over the same `verdict.py`/`equivalence.py`/`core.py` engine,
so the two bodies are short enough that this is a real, checked, low-risk
duplication, not a maintenance trap.

Root resolution follows `paths.py`'s own rule (the `TOLEDO_ROOT` environment
variable, else the checkout `mcp/` sits in) — there is no `--out-root` flag
here, unlike `scripts/toledo`, because every subcommand reads through the
process-wide `cache.get_cache()` singleton, which resolves its own root the
same way on every call.

This CLI's own JSON output shape is NOT wrapped in the `{"ok","data","error"}`
envelope `mcp/DESIGN.md` sec. 3 specifies for the MCP tool surface (that
envelope is a `server.py`/S2 change to the tool-call contract) — each
subcommand prints the plain, natural shape for its own answer (a row list,
an entry+verdict dict, `null` for "not registered"), documented per command
below.
"""
