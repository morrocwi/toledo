# ---------------------------------------------------------------------------
# TOON encode/decode (mcp/DESIGN.md sec. 7/14, graft B5/C7) — a small,
# dependency-free implementation of TOON's TABULAR form only (github.com/
# toon-format/toon). Per this workspace's own `toon-format` skill: the
# verified win is token count on UNIFORM row data (~35% fewer tokens than
# JSON, measured with the official encoder + real tiktoken) — nothing about
# accuracy is claimed, and this form is never applied to a single nested
# entry or a non-uniform structure (see every `--format toon` call site
# below: only on compact-entry row lists, never on `show`/`check`/`status`).
# `server.py` (S2) imports this pair rather than re-implementing it, per
# mcp/DESIGN.md sec. 7's "a single implementation, not two".
# ---------------------------------------------------------------------------

_TOON_HEADER_RE = re.compile(r"^\[(\d+)\]\{(.*)\}:$")


def _toon_needs_quote(cell: str, delimiter: str) -> bool:
    return (
        delimiter in cell
        or '"' in cell
        or "\n" in cell
        or cell != cell.strip()
        or cell == ""
    )


def _toon_escape(value: Any, delimiter: str) -> str:
    if value is None:
        return ""
    cell = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)
    if _toon_needs_quote(cell, delimiter):
        cell = '"' + cell.replace('"', '""') + '"'
    return cell


def _toon_split_row(line: str, delimiter: str) -> list[str]:
    """Minimal CSV-style split honouring the double-quote escaping
    `_toon_escape` writes — no third-party csv-sniffing, this format only
    ever has to round-trip what this module itself wrote."""
    cells: list[str] = []
    cur: list[str] = []
    in_quotes = False
    i = 0
    while i < len(line):
        ch = line[i]
        if in_quotes:
            if ch == '"':
                if i + 1 < len(line) and line[i + 1] == '"':
                    cur.append('"')
                    i += 1
                else:
                    in_quotes = False
            else:
                cur.append(ch)
        else:
            if ch == '"':
                in_quotes = True
            elif ch == delimiter:
                cells.append("".join(cur))
                cur = []
            else:
                cur.append(ch)
        i += 1
    cells.append("".join(cur))
    return cells


def encode_toon(rows: list[dict], *, delimiter: str = ",") -> str:
    """Encode a list of UNIFORM dict rows (every row the same field set, no
    nested non-uniform structure) as one TOON tabular block:

        [N]{field1,field2,...}:
          v1,v2,...
          v1,v2,...

    Field order is taken from the first row. A field a later row lacks
    encodes as an empty cell (never a KeyError) — the compact-entry rows
    this package emits are already uniform by construction (`core._summarize`
    / `queries._summarize`), so this is a safety margin, not the expected
    path. Empty input encodes as the valid, explicit `[0]{}:` (no rows to
    infer a header from)."""
    if not rows:
        return "[0]{}:"
    fields = list(rows[0].keys())
    header = f"[{len(rows)}]{{{delimiter.join(fields)}}}:"
    lines = [header]
    for row in rows:
        cells = [_toon_escape(row.get(f), delimiter) for f in fields]
        lines.append("  " + delimiter.join(cells))
    return "\n".join(lines)


def decode_toon(text: str, *, delimiter: str = ",") -> list[dict]:
    """Decode a block `encode_toon` produced. This package only ever emits
    TOON's tabular form (never the inline/keyed-tabular/list forms the full
    spec also defines), so this decoder only needs to understand that one —
    it is not a general TOON parser. Raises `ValueError` on anything else."""
    lines = [ln for ln in text.splitlines() if ln.strip()]
    if not lines:
        return []
    header = lines[0].strip()
    m = _TOON_HEADER_RE.match(header)
    if not m:
        raise ValueError(f"not a TOON tabular header (this decoder only reads that form): {header!r}")
    n = int(m.group(1))
    field_str = m.group(2)
    fields = field_str.split(delimiter) if field_str else []
    rows: list[dict] = []
    for line in lines[1 : 1 + n]:
        cells = _toon_split_row(line.strip(), delimiter)
        rows.append(dict(zip(fields, cells)))
    return rows


# ---------------------------------------------------------------------------
# Output helpers
# ---------------------------------------------------------------------------

def _emit(obj: Any) -> None:
    print(json.dumps(obj, indent=2, ensure_ascii=False))


def _emit_rows(rows: list[dict], fmt: str) -> None:
    if fmt == "toon":
        print(encode_toon(rows))
    else:
        _emit(rows)


def _die(message: str, code: int = 1) -> None:
    sys.stderr.write(f"error: {message}\n")
    raise SystemExit(code)


# ---------------------------------------------------------------------------
# Verdict wiring — deliberately NOT imported from server.py (see module
# docstring: server.py imports the TOON encoder from here, so the reverse
# import would cycle). Same two small helpers server.py's own
# `_resolver`/`_attach_verdict` implement, over this CLI's own cache handle.
# ---------------------------------------------------------------------------

def _resolver(c: "cache_mod.RegistryCache"):
    c.ensure_fresh()
    reg = c.registry
    return (lambda code: reg.by_code.get(code)) if reg else (lambda code: None)


def _attach_verdict(c: "cache_mod.RegistryCache", entry: dict | None) -> dict | None:
    if entry is None:
        return None
    return {"entry": entry, "verdict": verdict.verdict_for_entry(entry, _resolver(c)).to_dict()}


def _row_with_verdict(c: "cache_mod.RegistryCache", row: dict) -> dict:
    """This CLI's own extension over every row-list subcommand
    (`find`/`by-root`/`by-domain`/`by-record`/`descendants`): attach a
    compact `verdict`/`usable` pair per row. The founder rule this whole
    package exists to enforce ("every equation must be looked up before it
    is used") applies to a listing surface exactly as much as to a single
    `show`/`check` — a code printed by `toledo find` should not need a
    second command before a caller can tell whether it is safe to cite.
    `neighbours`' rows are relation edges, not citable entries in their own
    right (mirrors server.py's `toledo_neighbours` docstring: "the
    'relation' members are cross-links... and carry no verdict"), so
    `cmd_neighbours` below does not call this."""
    full = c.registry.by_code.get(row.get("code")) if c.registry else None
    if full is None:
        return row
    v = verdict.verdict_for_entry(full, _resolver(c))
    return {**row, "verdict": v.verdict, "usable": v.usable}


def _rows_with_verdict(c: "cache_mod.RegistryCache", rows: list[dict]) -> list[dict]:
    c.ensure_fresh()
    return [_row_with_verdict(c, r) for r in rows]


